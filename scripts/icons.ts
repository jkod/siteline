/**
 * Generates web/src/app/shared/ui/icons.generated.ts from web/icons.config.json: the path data
 * of only the Material Symbols the app uses, in the configured style, weight and fill. Run with
 * `npm run icons` after changing the config.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

interface IconConfig {
  style: 'outlined' | 'rounded' | 'sharp';
  weight: number;
  fill: boolean;
  icons: string[];
}

const root = new URL('..', import.meta.url).pathname;
const config = JSON.parse(readFileSync(join(root, 'web/icons.config.json'), 'utf8')) as IconConfig;
const pkg = `@material-symbols/svg-${config.weight}`;

let base: string;
try {
  base = dirname(createRequire(import.meta.url).resolve(`${pkg}/package.json`));
} catch {
  throw new Error(
    `Weight ${config.weight} needs ${pkg}: add it to apps/siteline/package.json and run npm install.`,
  );
}

const paths = config.icons.map((name) => {
  const file = join(base, config.style, `${name}${config.fill ? '-fill' : ''}.svg`);
  let svg: string;
  try {
    svg = readFileSync(file, 'utf8');
  } catch {
    throw new Error(
      `No Material Symbol named "${name}" in ${config.style}. Check https://fonts.google.com/icons.`,
    );
  }
  const d = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1]).join(' ');
  if (!d) throw new Error(`Unexpected SVG for "${name}"`);
  return [name, d] as const;
});

const out = `// Generated by scripts/icons.ts from web/icons.config.json. Don't edit by hand; run \`npm run icons\`.
// Material Symbols ${config.style}, weight ${config.weight}${config.fill ? ', filled' : ''}. Apache License 2.0.

export const ICON_PATHS = {
${paths.map(([name, d]) => `  ${/^[a-z_][a-z0-9_]*$/.test(name) ? name : `'${name}'`}: '${d}',`).join('\n')}
} as const;

export type IconName = keyof typeof ICON_PATHS;
`;
writeFileSync(join(root, 'web/src/app/shared/ui/icons.generated.ts'), out);
console.log(
  `Wrote ${paths.length} ${config.style} icons (weight ${config.weight}${config.fill ? ', filled' : ''}).`,
);
